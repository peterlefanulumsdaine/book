#!/usr/bin/env python3
"""Extract macro definitions whose bodies contain ^ or _ from macros.tex.

tex4ht makes ^ and _ active at \\begin{document} so it can emit <msub>/<msup>.
Macros defined in the preamble were tokenised before that, so their scripts
are invisible to tex4ht and come out flat ("p-1" for p^{-1}, "IdA" for
Id_A). hott-epub.cfg re-reads the definitions written by this script after the
catcode change, which fixes them.

Usage: script-macros.py macros.tex > out.tex
"""
import re
import sys

DEF_START = re.compile(r"\\(newcommand|renewcommand|def|gdef)\b\*?")


def balanced_end(src, i):
    """Index just past the brace group starting at src[i] == '{'."""
    depth = 0
    while i < len(src):
        c = src[i]
        if c == "\\":
            i += 2
            continue
        if c == "%":
            i = src.find("\n", i)
            if i < 0:
                return len(src)
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise ValueError("unbalanced braces")


def strip_comments(src):
    return re.sub(r"(?<!\\)%.*", "", src)


def definitions(src):
    i = 0
    while True:
        m = DEF_START.search(src, i)
        if not m:
            return
        kind = m.group(1)
        j = m.end()
        if kind in ("newcommand", "renewcommand"):
            # \newcommand{\name}[n][default]{body}
            if src[j] == "{":
                j = balanced_end(src, j)
            else:
                j = re.match(r"\\[A-Za-z@]+", src[j:]).end() + j
            while True:
                k = len(src[j:]) - len(src[j:].lstrip())
                if src[j + k] == "[":
                    j = src.index("]", j + k) + 1
                else:
                    j += k
                    break
        else:
            # \def\name<params>{body}
            name = re.match(r"\s*\\[A-Za-z@]+", src[j:])
            if not name:
                i = j
                continue
            j += name.end()
            j = src.index("{", j)
        end = balanced_end(src, j)
        yield kind, src[m.start():end], src[j:end]
        i = end


SCRIPT_CS = re.compile(r"([\^_])\s*(\\[A-Za-z]+)")


def brace_script_args(text):
    """Turn `^\\cmd{arg}` into `^{\\cmd{arg}}`.

    Once ^ and _ are active macros, `0^\\mathbf{w}` passes only `\\mathbf` as
    the script and leaves `{w}` dangling.
    """
    out, i = [], 0
    while True:
        m = SCRIPT_CS.search(text, i)
        if not m:
            out.append(text[i:])
            return "".join(out)
        j = m.end()
        while j < len(text) and text[j] == "{":
            j = balanced_end(text, j)
        out.append(text[i:m.start()])
        out.append(m.group(1) + "{" + text[m.start(2):j] + "}")
        i = j


MATHCLASS = re.compile(r"\\math(ord|bin|rel|op)\s*(?=\{)")


def unwrap_scripted_mathclass(text):
    """Turn `\\mathord{{p}^{-1}}` into `{{p}^{-1}}`.

    tex4ht renders \\mathord/\\mathbin/... as a single <mi>/<mo> token, so a
    script inside becomes <mi><msup>..</msup></mi>, which is invalid MathML.
    The bare group still forms a single atom.
    """
    out, i = [], 0
    while True:
        m = MATHCLASS.search(text, i)
        if not m:
            out.append(text[i:])
            return "".join(out)
        end = balanced_end(text, m.end())
        group = text[m.end():end]
        out.append(text[i:m.start()])
        out.append(group if ("^" in group or "_" in group) else text[m.start():end])
        i = end


ENSUREMATH_XSPACE = re.compile(r"\\ensuremath\s*(?=\{)")


def hottmath(text):
    """Turn `\\ensuremath{X}\\xspace` into `\\hottmath{X}` (see hott-epub.cfg).

    tex4ht's active _ peeks at the next *unexpanded* token to pair a
    subscript with a following superscript. In `\\refl{b_n}^n` that token is
    \\xspace, not ^, and the emitted <msub>/<msup> tags end up mismatched.
    \\hottmath leaves nothing behind in math mode.
    """
    out, i = [], 0
    while True:
        m = ENSUREMATH_XSPACE.search(text, i)
        if not m:
            out.append(text[i:])
            return "".join(out)
        end = balanced_end(text, m.end())
        rest = text[end:]
        out.append(text[i:m.start()])
        if rest.startswith("\\xspace"):
            out.append("\\hottmath" + text[m.end():end])
            i = end + len("\\xspace")
        else:
            out.append(text[m.start():end])
            i = end


def main():
    src = strip_comments(open(sys.argv[1], encoding="utf-8").read())
    print("% Generated by epub/script-macros.py from", sys.argv[1], "- do not edit.")
    print("\\makeatletter")
    for kind, text, body in definitions(src):
        if "^" not in body and "_" not in body:
            continue
        if kind == "newcommand":
            text = text.replace("\\newcommand", "\\renewcommand", 1)
        print(hottmath(unwrap_scripted_mathclass(brace_script_args(text))))
    print("\\makeatother")


if __name__ == "__main__":
    main()
